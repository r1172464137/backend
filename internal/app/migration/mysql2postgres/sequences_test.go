package mysql2postgres

import (
	"context"
	"database/sql"
	"fmt"
	"os"
	"testing"
	"time"
)

func postgresTestSchema(t *testing.T, db *sql.DB) string {
	t.Helper()
	schema := fmt.Sprintf("m2p_test_%d", time.Now().UnixNano())
	if _, err := db.ExecContext(context.Background(), "CREATE SCHEMA "+quotePGIdent(schema)); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if _, err := db.ExecContext(context.Background(), "DROP SCHEMA "+quotePGIdent(schema)+" CASCADE"); err != nil {
			t.Error(err)
		}
	})
	return schema
}

// --tables and --exclude bound every write, including sequence resets. A
// column that exists only in the target keeps its current sequence too.
func TestResetSequencesOnlyTouchesCopiedColumns(t *testing.T) {
	dsn := os.Getenv("PPANEL_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set PPANEL_TEST_POSTGRES_DSN for sequence scope coverage")
	}
	ctx := context.Background()
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { closeDatabase("postgres", db) })
	schema := postgresTestSchema(t, db)
	qualified := func(table string) string { return quotePGIdent(schema) + "." + quotePGIdent(table) }
	exec := func(query string, args ...any) {
		t.Helper()
		if _, err := db.ExecContext(ctx, query, args...); err != nil {
			t.Fatal(err)
		}
	}
	exec("CREATE TABLE " + qualified("copied") + " (id bigint GENERATED BY DEFAULT AS IDENTITY, target_only bigserial)")
	exec("CREATE TABLE " + qualified("empty") + " (id bigserial)")
	exec("CREATE TABLE " + qualified("excluded") + " (id bigserial)")
	exec("INSERT INTO " + qualified("copied") + " (id) VALUES (42)")
	exec("SELECT setval(pg_get_serial_sequence($1, $2), 77, true)", qualified("copied"), "target_only")
	exec("SELECT setval(pg_get_serial_sequence($1, $2), 900, true)", qualified("excluded"), "id")
	exec("SELECT setval(pg_get_serial_sequence($1, $2), 100, true)", qualified("empty"), "id")
	plans := []tablePlan{{Name: "copied"}, {Name: "empty"}}
	for i := range plans {
		columns, err := listPostgresColumns(ctx, db, schema, plans[i].Name)
		if err != nil {
			t.Fatal(err)
		}
		for _, col := range columns {
			if col.Name == "id" {
				plans[i].Columns = append(plans[i].Columns, col)
			}
		}
	}
	if err := resetSequences(ctx, db, schema, plans); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		table, column string
		want          int64
	}{{"copied", "id", 43}, {"copied", "target_only", 78}, {"empty", "id", 1}, {"excluded", "id", 901}} {
		var got int64
		if err := db.QueryRowContext(ctx, "SELECT nextval(pg_get_serial_sequence($1, $2))", qualified(tc.table), tc.column).Scan(&got); err != nil {
			t.Fatal(err)
		}
		if got != tc.want {
			t.Errorf("next %s.%s = %d, want %d", tc.table, tc.column, got, tc.want)
		}
	}
}
