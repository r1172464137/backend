func execSequenceSQL(t *testing.T, db *sql.DB, query string, args ...any) {
	t.Helper()
	if _, err := db.ExecContext(context.Background(), query, args...); err != nil {
		t.Fatalf("%s: %v", query, err)
	}
}

// Each real-engine test owns a schema, independent of concurrently running app
// migrations in public. The existing subset-copy test still uses its own public
// table and must succeed without creating any unrelated application tables.
func sequencePostgresFixture(t *testing.T) (*sql.DB, string) {
	t.Helper()
	dsn := os.Getenv("PPANEL_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("set PPANEL_TEST_POSTGRES_DSN to run real PostgreSQL sequence tests")
	}
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := db.Close(); err != nil {
			t.Error(err)
		}
	})
	schema := fmt.Sprintf("m2p_seq_%d", time.Now().UnixNano())
	execSequenceSQL(t, db, "CREATE SCHEMA "+quotePGIdent(schema))
	t.Cleanup(func() {
		execSequenceSQL(t, db, "DROP SCHEMA "+quotePGIdent(schema)+" CASCADE")
	})
	return db, schema
}

func assertNextSequenceValue(t *testing.T, db *sql.DB, schema, table string, want int64) {
	t.Helper()
	relation := quotePGIdent(schema) + "." + quotePGIdent(table)
	var got int64
	if err := db.QueryRowContext(context.Background(), `SELECT nextval(pg_get_serial_sequence($1, 'id')::regclass)`, relation).Scan(&got); err != nil {
		t.Fatal(err)
	}
	if got != want {
		t.Fatalf("%s next id = %d, want %d", relation, got, want)
	}
}

func seedUnselectedSequence(t *testing.T, db *sql.DB, schema, table string) {
	t.Helper()
	relation := quotePGIdent(schema) + "." + quotePGIdent(table)
	execSequenceSQL(t, db, "CREATE TABLE "+relation+" (id BIGSERIAL PRIMARY KEY)")
	execSequenceSQL(t, db, `SELECT setval(pg_get_serial_sequence($1, 'id')::regclass, 700, true)`, relation)
}

func assertUnselectedSequence(t *testing.T, db *sql.DB, schema, table string) {
	t.Helper()
	// Names are short and fixture-owned, so BIGSERIAL uses this sequence name.
	sequence := quotePGIdent(schema) + "." + quotePGIdent(table+"_id_seq")
	var last int64
	var called bool
	if err := db.QueryRowContext(context.Background(), "SELECT last_value, is_called FROM "+sequence).Scan(&last, &called); err != nil {
		t.Fatal(err)
	}
	if last != 700 || !called {
		t.Fatalf("unselected %s changed: last_value=%d is_called=%t", sequence, last, called)
	}
}

func TestResetSequencesPostgresSerialIdentityAndEmpty(t *testing.T) {
	db, schema := sequencePostgresFixture(t)
	prefix := quotePGIdent(schema) + "."
	execSequenceSQL(t, db, "CREATE TABLE "+prefix+"serial_id (id BIGSERIAL PRIMARY KEY)")
	execSequenceSQL(t, db, "INSERT INTO "+prefix+"serial_id (id) VALUES (41)")
	execSequenceSQL(t, db, "CREATE TABLE "+prefix+"identity_id (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)")
	execSequenceSQL(t, db, "INSERT INTO "+prefix+"identity_id (id) VALUES (84)")
	execSequenceSQL(t, db, "CREATE TABLE "+prefix+"empty_id (id BIGSERIAL PRIMARY KEY)")
	execSequenceSQL(t, db, `SELECT setval(pg_get_serial_sequence($1, 'id')::regclass, 99, true)`, prefix+"empty_id")
	seedUnselectedSequence(t, db, schema, "unselected")

	plans := []tablePlan{{Name: "serial_id"}, {Name: "identity_id"}, {Name: "empty_id"}}
	if err := resetSequences(context.Background(), db, schema, plans); err != nil {
		t.Fatal(err)
	}
	assertNextSequenceValue(t, db, schema, "serial_id", 42)
	assertNextSequenceValue(t, db, schema, "identity_id", 85)
	assertNextSequenceValue(t, db, schema, "empty_id", 1)
	assertUnselectedSequence(t, db, schema, "unselected")
}

// An unrestricted migration must still align every common table, not just the
// explicit --tables path. A target-only table's sequence must remain untouched.
func TestMigrateAlignsAllCommonTableSequences(t *testing.T) {
	mysqlDSN := os.Getenv("PPANEL_TEST_MYSQL_DSN")
	if mysqlDSN == "" {
		t.Skip("set PPANEL_TEST_MYSQL_DSN and PPANEL_TEST_POSTGRES_DSN to run the full-plan sequence test")
	}
	postgresDB, schema := sequencePostgresFixture(t)
	mysqlDB, err := sql.Open("mysql", normalizeMySQLDSN(mysqlDSN, time.UTC))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := mysqlDB.Close(); err != nil {
			t.Error(err)
		}
	})
	for _, kind := range []string{"serial", "identity"} {
		table := schema + "_" + kind
		execSequenceSQL(t, mysqlDB, "CREATE TABLE "+quoteMySQLIdent(table)+" (id BIGINT PRIMARY KEY)")
		t.Cleanup(func() {
			execSequenceSQL(t, mysqlDB, "DROP TABLE "+quoteMySQLIdent(table))
		})
		execSequenceSQL(t, mysqlDB, "INSERT INTO "+quoteMySQLIdent(table)+" (id) VALUES (42)")
		idType := "BIGSERIAL"
		if kind == "identity" {
			idType = "BIGINT GENERATED BY DEFAULT AS IDENTITY"
		}
		execSequenceSQL(t, postgresDB, "CREATE TABLE "+quotePGIdent(schema)+"."+quotePGIdent(table)+" (id "+idType+" PRIMARY KEY)")
	}
	targetOnly := schema + "_target_only"
	seedUnselectedSequence(t, postgresDB, schema, targetOnly)
	cfg := DefaultConfig()
	cfg.MySQLDSN, cfg.PostgresDSN = mysqlDSN, os.Getenv("PPANEL_TEST_POSTGRES_DSN")
	cfg.Schema, cfg.Location = schema, "Etc/UTC"
	if err := Migrate(context.Background(), cfg); err != nil {
		t.Fatal(err)
	}
	for _, kind := range []string{"serial", "identity"} {
		assertNextSequenceValue(t, postgresDB, schema, schema+"_"+kind, 43)
	}
	assertUnselectedSequence(t, postgresDB, schema, targetOnly)
}
